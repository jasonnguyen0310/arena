CREATE TABLE `trades` (
	`id` integer PRIMARY KEY AUTOINCREMENT NOT NULL,
	`opened_at` integer NOT NULL,
	`closed_at` integer,
	`ticker` text NOT NULL,
	`instrument` text NOT NULL,
	`direction` text NOT NULL,
	`planned_size` real NOT NULL,
	`planned_entry` real,
	`planned_stop` real,
	`planned_target` real,
	`thesis` text NOT NULL,
	`emotion_before` text NOT NULL,
	`conviction` integer NOT NULL,
	`actual_entry` real,
	`exit_price` real,
	`pnl` real,
	`outcome` text,
	`emotion_after` text,
	`market_context` text,
	`rules_followed` text,
	`rules_broken` text,
	`lesson` text
);
